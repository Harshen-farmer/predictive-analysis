CREATE TABLE transfer_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_department_id BIGINT NOT NULL REFERENCES department(id),
    to_department_id BIGINT NOT NULL REFERENCES department(id),
    resource_type VARCHAR(20) NOT NULL CHECK (resource_type IN ('BED', 'DOCTOR')),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    status VARCHAR(20) NOT NULL CHECK (status IN ('SUGGESTED', 'APPROVED', 'REJECTED')),
    decided_by VARCHAR(100),
    reason VARCHAR(255) NOT NULL
);
