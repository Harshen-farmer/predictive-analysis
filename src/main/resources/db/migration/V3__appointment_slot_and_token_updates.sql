ALTER TABLE appointment DROP CONSTRAINT uk_appointment_doctor_date_slot;
ALTER TABLE appointment ALTER COLUMN slot_time DROP NOT NULL;

CREATE TABLE appointment_token_counter (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL REFERENCES department(id),
    date DATE NOT NULL,
    last_token INTEGER NOT NULL,
    CONSTRAINT uk_appointment_token_department_date UNIQUE (department_id, date)
);

INSERT INTO appointment_token_counter (department_id, date, last_token)
SELECT department_id, date, MAX(token_number)
FROM appointment
GROUP BY department_id, date;
