CREATE TABLE department (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    total_beds INTEGER NOT NULL,
    avg_stay_days DOUBLE PRECISION NOT NULL,
    patients_per_doctor INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    created_by VARCHAR(100) NOT NULL
);

CREATE TABLE doctor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    department_id BIGINT NOT NULL REFERENCES department(id),
    work_start TIME NOT NULL,
    work_end TIME NOT NULL,
    slot_minutes INTEGER NOT NULL,
    on_duty BOOLEAN NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    created_by VARCHAR(100) NOT NULL
);

CREATE TABLE patient (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    age INTEGER NOT NULL,
    gender VARCHAR(30) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    created_by VARCHAR(100) NOT NULL
);

CREATE TABLE appointment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patient(id),
    doctor_id BIGINT NOT NULL REFERENCES doctor(id),
    department_id BIGINT NOT NULL REFERENCES department(id),
    date DATE NOT NULL,
    slot_time TIME NOT NULL,
    token_number INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('BOOKED', 'CHECKED_IN', 'COMPLETED', 'CANCELLED', 'NO_SHOW')),
    type VARCHAR(20) NOT NULL CHECK (type IN ('WALK_IN', 'EMERGENCY')),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    created_by VARCHAR(100) NOT NULL,
    CONSTRAINT uk_appointment_doctor_date_slot UNIQUE (doctor_id, date, slot_time)
);

CREATE TABLE bed (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bed_number VARCHAR(30) NOT NULL UNIQUE,
    department_id BIGINT NOT NULL REFERENCES department(id),
    status VARCHAR(20) NOT NULL CHECK (status IN ('AVAILABLE', 'OCCUPIED', 'MAINTENANCE')),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    created_by VARCHAR(100) NOT NULL
);

CREATE TABLE bed_allocation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patient(id),
    bed_id BIGINT NOT NULL REFERENCES bed(id),
    admit_date DATE NOT NULL,
    discharge_date DATE,
    allocated_by VARCHAR(100) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    created_by VARCHAR(100) NOT NULL
);

CREATE TABLE daily_load (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL REFERENCES department(id),
    date DATE NOT NULL,
    patient_count INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    created_by VARCHAR(100) NOT NULL,
    CONSTRAINT uk_daily_load_department_date UNIQUE (department_id, date)
);

CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN', 'STAFF')),
    enabled BOOLEAN NOT NULL,
    failed_attempts INTEGER NOT NULL,
    locked_until TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    created_by VARCHAR(100) NOT NULL
);

CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL,
    action VARCHAR(100) NOT NULL,
    entity_name VARCHAR(100) NOT NULL,
    entity_id VARCHAR(100) NOT NULL,
    event_timestamp TIMESTAMP NOT NULL
);

CREATE INDEX idx_daily_load_department_date ON daily_load (department_id, date);
CREATE INDEX idx_appointment_doctor_date ON appointment (doctor_id, date);
